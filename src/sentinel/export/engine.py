"""Review-drive export: CHECKING → PLANNING → COPYING → VERIFYING → MANIFEST → EJECTING → COMPLETE.

See docs/04 §6 and :mod:`sentinel.export.ledger` for the state machine. Every outcome is one
of: COMPLETE (every file read back and verified, manifests written and read back), FAILED
(needs a person; operator alert E-0xx; retried on the same drive), INTERRUPTED (the drive
vanished; resumed when the same drive is presented again), or nothing to export.

Rules enforced here:
* local recordings are only read, never modified or deleted; they are re-hashed against their
  sealed SHA-256 before an MP4 is made from them or decoded for comparison;
* a file that already exists on the drive is never overwritten: same content → re-verified
  and recorded (``already_present``), different content → explicit conflict (E-004);
* COMPLETE requires **byte verification of every file**: read back from the drive bypassing the
  OS cache and compared with a SHA-256 known before the read (originals: sealed hash; MP4s:
  hash of the file as FFmpeg wrote it; documents: hash of the generated bytes);
* MP4s additionally get the configured decoded-picture check (full / sampled / deferred, see
  :mod:`sentinel.export.contentcheck`); the level each MP4 got is recorded in the manifest;
* on resume, already-verified files are re-hashed (no decode) and must still match;
* an MP4's file hash is never compared with, or reported as, an original's hash.
"""

